"""One command to build the shippable release: the app, then the installer.

    python scripts/build_release.py

Steps, in order:
  1. generate build/version_info.txt from ml_data_view.__version__
  2. PyInstaller (onedir)  -> dist/MLDatasetProfiler/
  3. Inno Setup            -> dist/MLDatasetProfiler-Setup-<version>.exe

The version is injected into the .iss on the command line rather than
duplicated in it, so `__version__` stays the only place a release number
is written down.

Fails loudly and early — a missing Inno Setup names the winget command
rather than leaving a dist/ that looks finished but has no installer in it.
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import ml_data_view  # noqa: E402
from ml_data_view.resources import PROJECT_ROOT  # noqa: E402

SPEC = PROJECT_ROOT / "MLDatasetProfiler.spec"
ISS = PROJECT_ROOT / "installer" / "MLDatasetProfiler.iss"
BUILD_DIR = PROJECT_ROOT / "build"
DIST_DIR = PROJECT_ROOT / "dist"
VERSION_INFO = BUILD_DIR / "version_info.txt"

# Inno Setup 6 installs per-user by default (to %LOCALAPPDATA%\Programs),
# which is where winget puts it; the Program Files paths cover a
# machine-wide install done by hand.
ISCC_CANDIDATES = [
    Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
    Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
    Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
]


def version_tuple() -> tuple[int, int, int, int]:
    """`0.1.0` -> `(0, 1, 0, 0)`. Win32 VERSIONINFO wants four parts."""
    major, minor, patch = (int(part) for part in ml_data_view.__version__.split("."))
    return major, minor, patch, 0


def render_version_info() -> str:
    """The Win32 VERSIONINFO resource PyInstaller embeds in the .exe.

    Without this, right-clicking the executable and opening Properties >
    Details shows nothing at all — no product name, no publisher, no
    version. Windows also has nothing to show in Add/Remove Programs
    beyond a bare name.
    """
    numbers = version_tuple()
    version = ml_data_view.__version__
    return f"""# Generated by scripts/build_release.py — do not edit.
# Source of truth: ml_data_view.__version__
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={numbers},
    prodvers={numbers},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [StringStruct('CompanyName', {ml_data_view.PUBLISHER!r}),
         StringStruct('FileDescription', {ml_data_view.APP_NAME!r}),
         StringStruct('FileVersion', {version!r}),
         StringStruct('InternalName', 'MLDatasetProfiler'),
         StringStruct('LegalCopyright', {ml_data_view.COPYRIGHT!r}),
         StringStruct('OriginalFilename', 'MLDatasetProfiler.exe'),
         StringStruct('ProductName', {ml_data_view.APP_NAME!r}),
         StringStruct('ProductVersion', {version!r})])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def iss_defines() -> dict[str, str]:
    """Values passed to ISCC with /D, so the .iss hard-codes no version."""
    return {
        "MyAppName": ml_data_view.APP_NAME,
        "MyAppVersion": ml_data_view.__version__,
        "MyAppPublisher": ml_data_view.PUBLISHER,
    }


def find_iscc() -> Path:
    for candidate in ISCC_CANDIDATES:
        if candidate.is_file():
            return candidate
    raise SystemExit(
        "Inno Setup 6 not found (looked for ISCC.exe in:\n  "
        + "\n  ".join(str(c) for c in ISCC_CANDIDATES)
        + "\n\nInstall it with:  winget install JRSoftware.InnoSetup"
    )


def _run(command: list[str], label: str) -> None:
    print(f"\n=== {label} ===")
    print("  " + subprocess.list2cmdline(command))
    result = subprocess.run(command, cwd=PROJECT_ROOT)
    if result.returncode != 0:
        raise SystemExit(f"{label} failed (exit {result.returncode})")


def _size(path: Path) -> str:
    total = (
        sum(f.stat().st_size for f in path.rglob("*") if f.is_file())
        if path.is_dir()
        else path.stat().st_size
    )
    return f"{total / (1024 * 1024):.1f} MB"


def main() -> int:
    print(f"ML Dataset Profiler {ml_data_view.__version__}")

    BUILD_DIR.mkdir(exist_ok=True)
    VERSION_INFO.write_text(render_version_info(), encoding="utf-8")
    print(f"wrote {VERSION_INFO.relative_to(PROJECT_ROOT)}")

    _run(
        [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", str(SPEC)],
        "PyInstaller (onedir)",
    )

    app_dir = DIST_DIR / "MLDatasetProfiler"
    if not (app_dir / "MLDatasetProfiler.exe").is_file():
        raise SystemExit(f"expected {app_dir / 'MLDatasetProfiler.exe'} — onedir build did not produce it")

    iscc = find_iscc()
    defines = [f"/D{key}={value}" for key, value in iss_defines().items()]
    _run([str(iscc), *defines, str(ISS)], "Inno Setup")

    setup = DIST_DIR / f"MLDatasetProfiler-Setup-{ml_data_view.__version__}.exe"
    print("\n=== built ===")
    print(f"  app        {app_dir}  ({_size(app_dir)})")
    if setup.is_file():
        print(f"  installer  {setup}  ({_size(setup)})")
    else:
        raise SystemExit(f"installer missing: expected {setup}")
    print("\nThe installer is UNSIGNED — Windows SmartScreen will warn on first run.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
